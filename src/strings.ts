const TABLES: Record<Language, Partial<Strings>> = { en, pt, es };

export function pickLanguage(locale: string | undefined): Language {
  const base = (locale ?? "en").toLowerCase().split(/[-_]/)[0];
  return base in TABLES ? (base as Language) : "en";
}

export function stringsFor(language: Language): Strings {
  return { ...en, ...TABLES[language] };
}

/** A string with its {name} slots filled. */
export function fill(text: string, values: Record<string, string | number>): string {
  return text.replace(/\{(\w+)\}/g, (all, name: string) => (name in values ? String(values[name]) : all));
}
